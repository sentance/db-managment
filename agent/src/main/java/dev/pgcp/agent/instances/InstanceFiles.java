package dev.pgcp.agent.instances;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Pattern;

import dev.pgcp.agent.api.AgentApi;
import dev.pgcp.agent.api.InstanceSpec;
import dev.pgcp.agent.config.AgentException;

/** Renders the files of a managed instance. Inputs are validated here, so rendering never needs escaping. */
final class InstanceFiles {

    static final Pattern SETTING_KEY = Pattern.compile("^[a-z][a-z0-9_]{1,62}$");
    static final Pattern SETTING_VALUE = Pattern.compile("^[A-Za-z0-9._:-]{1,64}$");
    static final Pattern IPV4 = Pattern.compile("^(25[0-5]|2[0-4]\\d|1?\\d?\\d)(\\.(25[0-5]|2[0-4]\\d|1?\\d?\\d)){3}$");
    static final Pattern HOSTNAME = Pattern.compile("^(?=.{1,253}$)[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?(\\.[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?)*$");

    /** Parameters the agent controls itself; callers cannot override them. */
    static final Set<String> RESERVED_SETTINGS = Set.of("hba_file", "ident_file", "config_file", "data_directory", "port",
            "listen_addresses", "ssl", "ssl_cert_file", "ssl_key_file", "ssl_ca_file", "ssl_min_protocol_version",
            "password_encryption", "archive_mode", "archive_command", "restore_command", "unix_socket_directories",
            "external_pid_file", "include", "include_dir");

    static final String SRC_DIR = "/etc/pgcp-src";
    static final String RUNTIME_DIR = "/etc/pgcp";
    static final String PASSWORD_PLACEHOLDER = "scrubbed-after-initdb\n";

    private InstanceFiles() {
    }

    static void validate(InstanceSpec s) {
        if (s.instanceId() == null) {
            throw AgentException.badRequest("instanceId is required");
        }
        try {
            AgentApi.requireValidInstanceName(s.name());
            AgentApi.requireSupportedMajor(s.pgMajor());
        } catch (IllegalArgumentException e) {
            throw AgentException.badRequest(e.getMessage());
        }
        if (s.memoryMb() < 256 || s.memoryMb() > 262_144) {
            throw AgentException.badRequest("memoryMb must be between 256 and 262144");
        }
        if (s.cpus() < 0.1 || s.cpus() > 128) {
            throw AgentException.badRequest("cpus must be between 0.1 and 128");
        }
        if (s.shmMb() < 64 || s.shmMb() > 16_384) {
            throw AgentException.badRequest("shmMb must be between 64 and 16384");
        }
        if (s.bindAddress() != null) {
            if (!IPV4.matcher(s.bindAddress()).matches()) {
                throw AgentException.badRequest("bindAddress must be an IPv4 address");
            }
            if (s.hostPort() == null || s.hostPort() < 1024 || s.hostPort() > 65_535) {
                throw AgentException.badRequest("hostPort must be between 1024 and 65535");
            }
        } else if (s.hostPort() != null) {
            throw AgentException.badRequest("hostPort requires bindAddress");
        }
        for (String n : nullToEmpty(s.extraNetworks())) {
            if (!AgentApi.NETWORK_NAME.matcher(n).matches() || Set.of("host", "none").contains(n)
                    || AgentApi.INTERNAL_NETWORK.equals(n)) {
                throw AgentException.badRequest("invalid extra network: " + n);
            }
        }
        for (String h : nullToEmpty(s.tlsHostnames())) {
            if (!HOSTNAME.matcher(h).matches()) {
                throw AgentException.badRequest("invalid TLS hostname: " + h);
            }
        }
        if (s.superuserPassword() == null || !s.superuserPassword().matches("^[A-Za-z0-9]{24,128}$")) {
            throw AgentException.badRequest("superuserPassword must be 24-128 alphanumeric characters");
        }
        if (s.settings() != null) {
            s.settings().forEach((k, v) -> {
                if (!SETTING_KEY.matcher(k).matches() || RESERVED_SETTINGS.contains(k)) {
                    throw AgentException.badRequest("setting not allowed: " + k);
                }
                if (v == null || !SETTING_VALUE.matcher(v).matches()) {
                    throw AgentException.badRequest("invalid value for setting " + k);
                }
            });
        }
    }

    /** True when the published port is reachable from outside the host, which requires TLS for every remote client. */
    static boolean publiclyExposed(InstanceSpec s) {
        return s.bindAddress() != null && !s.bindAddress().startsWith("127.");
    }

    static String pgHba(InstanceSpec s) {
        String remote = publiclyExposed(s) ? "hostssl" : "host   ";
        return """
                # Generated by pgcp-agent. Do not edit: changes are overwritten on reconfigure.
                # TYPE  DATABASE  USER      ADDRESS        METHOD
                local   all       postgres                 peer
                local   all       all                      scram-sha-256
                host    all       all       127.0.0.1/32   scram-sha-256
                host    all       all       ::1/128        scram-sha-256
                %1$s all       all       0.0.0.0/0      scram-sha-256
                %1$s all       all       ::/0           scram-sha-256
                """.formatted(remote);
    }

    static String pgIdent() {
        return "# Generated by pgcp-agent. Intentionally empty.\n";
    }

    static Map<String, String> effectiveSettings(InstanceSpec s) {
        Map<String, String> settings = new LinkedHashMap<>();
        settings.put("listen_addresses", "*");
        settings.put("hba_file", RUNTIME_DIR + "/pg_hba.conf");
        settings.put("ident_file", RUNTIME_DIR + "/pg_ident.conf");
        settings.put("ssl", "on");
        settings.put("ssl_cert_file", RUNTIME_DIR + "/server.crt");
        settings.put("ssl_key_file", RUNTIME_DIR + "/server.key");
        settings.put("ssl_min_protocol_version", "TLSv1.2");
        settings.put("password_encryption", "scram-sha-256");
        if (s.settings() != null) {
            new java.util.TreeMap<>(s.settings()).forEach(settings::put);
        }
        return settings;
    }

    static String compose(InstanceSpec s, String image) {
        String container = AgentApi.containerName(s.name());
        // PostgreSQL 18 images declare the volume one level up (PGDATA=/var/lib/postgresql/18/docker).
        String dataMount = s.pgMajor() >= 18 ? "/var/lib/postgresql" : "/var/lib/postgresql/data";
        StringBuilder y = new StringBuilder();
        y.append("# Generated by pgcp-agent for instance ").append(s.instanceId()).append(".\n");
        y.append("# Manual recovery when the panel is down:  docker compose -f compose.yml up -d\n");
        y.append("name: ").append(container).append('\n');
        y.append("services:\n");
        y.append("  postgres:\n");
        y.append("    image: \"").append(image).append("\"\n");
        y.append("    container_name: \"").append(container).append("\"\n");
        y.append("    hostname: \"").append(container).append("\"\n");
        y.append("    restart: unless-stopped\n");
        y.append("    stop_grace_period: 2m\n");
        y.append("    labels:\n");
        y.append("      ").append(AgentApi.LABEL_MANAGED).append(": \"true\"\n");
        y.append("      ").append(AgentApi.LABEL_INSTANCE_ID).append(": \"").append(s.instanceId()).append("\"\n");
        y.append("      ").append(AgentApi.LABEL_PG_MAJOR).append(": \"").append(s.pgMajor()).append("\"\n");
        y.append("    environment:\n");
        y.append("      POSTGRES_USER: \"postgres\"\n");
        y.append("      POSTGRES_PASSWORD_FILE: \"").append(RUNTIME_DIR).append("/superuser-password\"\n");
        y.append("      POSTGRES_INITDB_ARGS: \"--auth-local=peer --auth-host=scram-sha-256 --data-checksums\"\n");
        y.append("    command:\n");
        y.append("      - \"postgres\"\n");
        effectiveSettings(s).forEach((k, v) -> {
            y.append("      - \"-c\"\n");
            y.append("      - \"").append(k).append('=').append(v).append("\"\n");
        });
        y.append("    volumes:\n");
        y.append("      - \"pgdata:").append(dataMount).append("\"\n");
        y.append("      - \"./config:").append(SRC_DIR).append(":ro\"\n");
        y.append("    shm_size: \"").append(s.shmMb()).append("m\"\n");
        y.append("    mem_limit: \"").append(s.memoryMb()).append("m\"\n");
        y.append("    cpus: ").append(s.cpus()).append('\n');
        if (s.bindAddress() != null) {
            y.append("    ports:\n");
            y.append("      - \"").append(s.bindAddress()).append(':').append(s.hostPort()).append(":5432\"\n");
        }
        y.append("    networks:\n");
        y.append("      - \"").append(AgentApi.INTERNAL_NETWORK).append("\"\n");
        for (String n : nullToEmpty(s.extraNetworks())) {
            y.append("      - \"").append(n).append("\"\n");
        }
        y.append("    healthcheck:\n");
        y.append("      test: [\"CMD\", \"pg_isready\", \"-h\", \"127.0.0.1\", \"-p\", \"5432\", \"-U\", \"postgres\"]\n");
        y.append("      interval: 5s\n");
        y.append("      timeout: 5s\n");
        y.append("      retries: 12\n");
        y.append("      start_period: 60s\n");
        y.append("    logging:\n");
        y.append("      driver: json-file\n");
        y.append("      options:\n");
        y.append("        max-size: \"20m\"\n");
        y.append("        max-file: \"5\"\n");
        y.append("volumes:\n");
        y.append("  pgdata:\n");
        y.append("    name: \"").append(AgentApi.volumeName(s.name())).append("\"\n");
        y.append("    labels:\n");
        y.append("      ").append(AgentApi.LABEL_MANAGED).append(": \"true\"\n");
        y.append("      ").append(AgentApi.LABEL_INSTANCE_ID).append(": \"").append(s.instanceId()).append("\"\n");
        y.append("networks:\n");
        y.append("  ").append(AgentApi.INTERNAL_NETWORK).append(":\n");
        y.append("    external: true\n");
        for (String n : nullToEmpty(s.extraNetworks())) {
            y.append("  ").append(n).append(":\n");
            y.append("    external: true\n");
        }
        return y.toString();
    }

    private static List<String> nullToEmpty(List<String> l) {
        return l == null ? List.of() : l;
    }
}
